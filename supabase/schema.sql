-- Run this script in Supabase Dashboard > SQL Editor.
create table if not exists public.run_tb (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  place text not null,
  distance_km numeric(7, 2) not null check (distance_km > 0),
  duration_minutes integer not null check (duration_minutes > 0),
  run_date date not null default current_date,
  note text not null default '',
  image_path text,
  created_at timestamptz not null default now()
);

alter table public.run_tb enable row level security;
grant usage on schema public to authenticated;
grant select, insert, update, delete on public.run_tb to authenticated;

create policy "Users can read their own runs"
  on public.run_tb for select to authenticated
  using (auth.uid() = user_id);

create policy "Users can add their own runs"
  on public.run_tb for insert to authenticated
  with check (auth.uid() = user_id);

create policy "Users can update their own runs"
  on public.run_tb for update to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

create policy "Users can delete their own runs"
  on public.run_tb for delete to authenticated
  using (auth.uid() = user_id);

insert into storage.buckets (id, name, public)
values ('run-images', 'run-images', false)
on conflict (id) do nothing;

create policy "Users can read their own run images"
  on storage.objects for select to authenticated
  using (bucket_id = 'run-images' and (storage.foldername(name))[1] = auth.uid()::text);

create policy "Users can upload their own run images"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'run-images' and (storage.foldername(name))[1] = auth.uid()::text);

create policy "Users can update their own run images"
  on storage.objects for update to authenticated
  using (bucket_id = 'run-images' and (storage.foldername(name))[1] = auth.uid()::text)
  with check (bucket_id = 'run-images' and (storage.foldername(name))[1] = auth.uid()::text);

create policy "Users can delete their own run images"
  on storage.objects for delete to authenticated
  using (bucket_id = 'run-images' and (storage.foldername(name))[1] = auth.uid()::text);
